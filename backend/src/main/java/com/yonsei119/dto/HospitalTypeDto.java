package com.yonsei119.dto;

/**
 * ============================================================================
 * [레코드 역할]
 * 응급의료기관의 종별 분류(상급종합 / 권역응급 / 일반·기타) 메타데이터를 담는 DTO입니다.
 *
 * [담당 기능]
 * 1. 프론트엔드 필터 체크박스(`tertiary`, `regional`, `other`)와 매칭되는 그룹 키를 제공합니다.
 * 2. 지도 마커 및 상세 시트 배지에 표시할 한글 라벨(`상급종합`, `권역응급`, `일반·기타`)과
 *    강조 색상(`accent`), 정렬 우선순위(`priority`)를 제공합니다.
 *
 * [수정 시 영향 및 예시]
 * - 만약 '권역외상센터'를 별도의 4번째 종별 그룹으로 분리하고 싶다면:
 *   `HospitalClassifier`에서 `new HospitalTypeDto("trauma", "권역외상", "#2563eb", 1)`을
 *   반환하도록 확장할 수 있습니다.
 * ============================================================================
 *
 * @param group    필터 식별 코드 (`"tertiary"`, `"regional"`, `"other"`)
 * @param label    화면 표시용 한글 종별 라벨 (`"상급종합"`, `"권역응급"`, `"일반·기타"`)
 * @param accent   종별 대표 HEX 색상 코드 (`"#111111"`, `"#ff3b30"`, `"#64748b"`)
 * @param priority 정렬 우선순위 (낮을수록 우선: 상급종합 `0`, 권역응급 `1`, 일반·기타 `2`)
 */
public record HospitalTypeDto(
        String group,
        String label,
        String accent,
        int priority
) {
}
